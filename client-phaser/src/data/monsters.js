/**
 * Creates a ready-to-battle Monsver instance.
 * @param {string} id
 * @param {number} level
 * @returns {object}
 */
export function createMonsterInstance(id, level = 5) {
  const def = MONSTERS[id] ?? MONSTERS.pyrofang;
  const scale = 1 + (level - 1) * 0.12;
  const maxHp = Math.round(def.baseHp * scale);
  const maxSp = def.maxSp ?? 40;
  return {
    id: def.id,
    name: def.name,
    element: def.element,
    level,
    xp: 0,
    xpToNext: level * 50,
    maxHp,
    currentHp: maxHp,
    maxSp,
    currentSp: maxSp,
    attack: Math.round(def.baseAttack * scale),
    defense: Math.round(def.baseDefense * scale),
    speed: Math.round(def.baseSpeed * scale),
    status: 'None',
    statusTurns: 0,
    guarding: false,
    evolvesAt: def.evolvesAt,
    evolvesTo: def.evolvesTo,
    skills: [...def.skills],
  };
}
